// Generates the practice levels shipped inside the app and the API (so both agree on every level).
//   node build-levels.mjs
// Output is deterministic: running it again changes nothing unless the generator changes.
// Levels are generated in parallel worker threads (Zip's bigger boards take a while).
import { mkdirSync, writeFileSync } from 'node:fs';
import { availableParallelism } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { TRACKS, LEVELS_PER_GAME, practiceLevel, solve } from './games.mjs';

if (!isMainThread) {
  const { game, levels } = workerData; // game here is a track
  const out = levels.map((level) => {
    const puzzle = practiceLevel(game, level);
    if (solve(game, puzzle).count !== 1) throw new Error(`${game} level ${level} does not have exactly one solution`);
    return puzzle;
  });
  parentPort.postMessage(out);
} else {
  const root = new URL('../../../', import.meta.url);
  const workers = Math.max(1, availableParallelism());
  const jobs = [];
  for (const game of TRACKS) {
    // Interleaved chunks, so every worker gets a similar mix of easy and hard levels.
    for (let w = 0; w < workers; w++) {
      const levels = [];
      for (let level = 1 + w; level <= LEVELS_PER_GAME; level += workers) levels.push(level);
      jobs.push(
        new Promise((resolve, reject) => {
          const worker = new Worker(new URL(import.meta.url), { workerData: { game, levels } });
          worker.once('message', (puzzles) => resolve({ game, levels, puzzles }));
          worker.once('error', reject);
        }),
      );
    }
  }
  const results = await Promise.all(jobs);
  for (const game of TRACKS) {
    const levels = new Array(LEVELS_PER_GAME);
    for (const r of results.filter((x) => x.game === game)) r.levels.forEach((level, i) => (levels[level - 1] = r.puzzles[i]));
    const json = JSON.stringify(levels);

    const [base, ...rest] = game.split('-');
    const webDir = new URL(`apps/web/src/app/games/${base}/`, root);
    mkdirSync(webDir, { recursive: true });
    writeFileSync(new URL(rest.length ? `levels-${rest.join('-')}.data.ts` : 'levels.data.ts', webDir), `// Generated by tools/generators/puzzles/build-levels.mjs. Do not edit.\nexport const LEVELS: unknown[] = ${json};\n`);

    const apiDir = new URL('apps/api/Zenigma.Api/Games/Puzzles/levels/', root);
    mkdirSync(apiDir, { recursive: true });
    writeFileSync(new URL(`${game}.json`, apiDir), json);
    console.log(`${game}: ${levels.length} levels, ${(json.length / 1024).toFixed(0)} KB`);
  }
}

// Builds the Wend word lists (3 to 6 letters) from the same open sources as build.mjs:
//   VALID  every dictionary word of 3 to 6 letters that is not profane (what a player may trace)
//   COMMON the everyday ones, by how often people use them (what the daily puzzles are made from)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const dictionary = new Set(readFileSync(new URL('./node_modules/word-list/words.txt', import.meta.url), 'utf8').split('\n').map((w) => w.trim()));
const frequencies = require('subtlex-word-frequencies');
const profane = new Set(require('profane-words').map((w) => w.toLowerCase()));
const excluded = new Set(readFileSync(new URL('./exclude.txt', import.meta.url), 'utf8').split('\n').filter(Boolean));

const fits = (w) => /^[a-z]{3,6}$/.test(w);
const has = (x) => dictionary.has(x);
const looksInflected = (w) => {
  if (w.endsWith('ies') && has(w.slice(0, -3) + 'y')) return true;
  if (w.endsWith('es') && (has(w.slice(0, -2)) || has(w.slice(0, -1)))) return true;
  if (w.endsWith('s') && !w.endsWith('ss') && !w.endsWith('us') && !w.endsWith('is') && has(w.slice(0, -1))) return true;
  if (w.endsWith('ed') && (has(w.slice(0, -1)) || has(w.slice(0, -2)))) return true;
  if (w.endsWith('ing') && (has(w.slice(0, -3)) || has(w.slice(0, -3) + 'e'))) return true;
  return false;
};

const valid = [...dictionary].filter((w) => fits(w) && !profane.has(w)).sort();

const PER_LENGTH = { 3: 260, 4: 650, 5: 900, 6: 900 };
const seen = new Set();
const byLength = { 3: [], 4: [], 5: [], 6: [] };
for (const { word, count } of frequencies.slice().sort((a, b) => b.count - a.count)) {
  const w = word.toLowerCase();
  if (word !== w || seen.has(w) || !fits(w) || !has(w) || profane.has(w) || excluded.has(w) || looksInflected(w)) continue;
  seen.add(w);
  if (byLength[w.length].length < PER_LENGTH[w.length]) byLength[w.length].push(w);
}
const common = Object.values(byLength).flat().sort();

const out = new URL('../../../apps/web/src/app/games/mind/data/', import.meta.url);
import { mkdirSync } from 'node:fs';
mkdirSync(out, { recursive: true });
const asModule = (name, words, doc) => `/* Generated by tools/generators/words/build-wend.mjs. Do not edit. */\n/** ${doc} */\nexport const ${name}: string = '${words.join('\\n')}';\n`;
writeFileSync(new URL('wend-valid.ts', out), asModule('WEND_VALID', valid, 'Every word of 3 to 6 letters a player may trace.'));
writeFileSync(new URL('wend-common.ts', out), asModule('WEND_COMMON', common, 'Everyday words of 3 to 6 letters that puzzles are made from.'));
console.log('valid', valid.length, 'common', common.length, Object.fromEntries(Object.entries(byLength).map(([k, v]) => [k, v.length])));
